# ── 1단계: Gemini 영상 읽기(판정 + 관찰 기록) ─────────────────────────

OBSERVE_PROMPT = """\
너는 유튜브 쇼츠 영상에서 장소 정보의 근거를 찾는 분석기다. 화면·자막·음성을 모두 근거로 쓴다.

## 형식 판정
- is_vertical: 세로 화면(쇼츠 형식)이면 true, 가로 화면이면 false.
- is_longform: 영상이 3분(3:00)을 넘어 계속되면 true.

## 영상 판정 (verdict)
- "롱폼": is_vertical=false 이거나 is_longform=true.
- "해외": 영상에서 찾아낸 장소가 대한민국이 아님.
- "장소 아님": 카페·디저트·맛집·술집·팝업·편집샵·전시·공연·축제·레저·스포츠·산책·명소 같은
  방문할 장소로 구분할 수 없는 영상(브이로그·리액션 등).
- "장소": 위에 해당하지 않음.
"장소"가 아니면 observations 는 빈 목록으로 두고 끝낸다.

## 업로드 날짜 (upload_date)
영상이 유튜브에 올라온 날짜. 확인할 수 없으면 null 로 둔다. 짐작해서 채우지 않는다.

## 관찰 기록 (observations)

시각 순서대로 한 줄에 하나씩 "MM:SS 출처 - 내용" 형식으로 적는다.
출처는 다음 중 하나를 쓴다: 간판, 현수막, 메뉴판, 포장지, 벽면 문구, 차량 표기, 로고(티셔츠·모자·앞치마 등),
자막, 해시태그, 음성, 장면.

- 화면 속 글자는 자막(하단 텍스트·말풍선)과 자막이 아닌 글자(간판·현수막·메뉴판·포장지·로고 등)를 구분해 적는다.
  상호는 대개 자막이 아닌 글자에 있다. 화면을 끝까지 본다.
- 글자가 흐릿하면 읽히는 대로 적고 끝에 "(흐림)"을 붙인다.
- 음성: 장소 이름·위치·메뉴·가격·기간처럼 정보가 되는 말을 옮긴다.
- 장면: 무엇이 비치는지 적는다 — 음식인지 음료인지 빵인지, 실내인지 실외인지, 무대·전시물·풍경·사람들의 활동.
- 영상에서 확인되지 않은 것은 적지 않는다. 네가 이미 알고 있는 지식으로 짐작한 것은 확인이 아니다.
- "장소"인 영상은 장소를 찾고 성격을 판단하는 데 근거가 되는 것만 적는다 — 상호·위치·기간이 드러난 글자와 말,
  무엇을 파는 곳인지 보여 주는 장면. 장소가 여러 곳이면 모든 장소의 근거를 적는다.

## 영상이 여러 개일 때
영상마다 앞에 [영상 N] 번호가 붙어 있다. 영상마다 결과를 하나씩, 번호 순서대로 낸다.
video_index 에는 그 번호를 그대로 적는다. 영상을 건너뛰지 않는다. 영상끼리 정보를 섞지 않는다.
"""


# 영상 개수가 호출마다 달라서 {video_url} 템플릿 하나로는 표현이 안 된다.
# 영상마다 앞에 [영상 N] 라벨을 붙여 메시지를 코드로 조립한다.
def build_observe_messages(video_urls: list[str]) -> list[BaseMessage]:
    content: list[dict] = [
        {"type": "text", "text": f"영상 {len(video_urls)}개를 각각 분석해라."}
    ]
    for i, url in enumerate(video_urls, start=1):
        content.append({"type": "text", "text": f"[영상 {i}]"})
        # "video" 블록은 구간 지정(video_metadata)을 받지 않아 "media" 블록으로 보낸다.
        content.append({
            "type": "media",
            "file_uri": url,
            "video_metadata": {"end_offset": f"{settings.ANALYZE_VIDEO_MAX_SECONDS}s"},
        })

    return [
        SystemMessage(content=OBSERVE_PROMPT),
        HumanMessage(content=content),
    ]


# ── 2단계: GPU Gemma 장소 추출(영상 하나당 호출 1번) ──────────────────

EXTRACT_PROMPT = """\
너는 유튜브 쇼츠 영상의 관찰 기록을 읽고 장소 정보를 뽑는 분석기다. 영상은 볼 수 없고 관찰 기록만 근거로 쓴다.
관찰 기록은 시각 순서대로 "MM:SS 출처 - 내용" 한 줄씩이다. 이 영상은 장소 영상으로 이미 판정됐다.

## 원칙

관찰 기록에서 확인되지 않은 것은 비워 둔다. 추측해서 채우지 않는다.
네가 이미 알고 있는 지식으로 짐작한 것은 확인이 아니다.
영상에 방문할 장소가 여러 곳 나오면 장소마다 결과를 따로 낸다. 개수를 줄이거나
대표 한 곳만 고르지 않는다. 각 결과의 지역·요약·신뢰도는 그 장소에 대한 것이다.
장소를 특정하지 못하면 장소명을 비운 결과를 하나만 낸다.

값을 적을 때마다 스스로 답한다 — **이 정보가 관찰 기록의 어느 줄에서 나왔는가.**
답할 수 없으면 아직 확인한 것이 아니다.

## 장소명

상호는 자막에 잘 나오지 않는다. 대개 간판·현수막·메뉴판·포장지·로고처럼 자막이 아닌 글자 줄에 있다.
자막에 없다는 이유로 비우지 마라. 관찰 기록을 끝까지 본다.

"(흐림)"이 붙은 글자도 **읽힌 대로 적고 신뢰도를 낮춘다.**
뒤따르는 검증 단계는 이름이 있어야 검색할 수 있다 — 철자가 조금
틀린 이름이 빈 값보다 낫다.

## 행사 날짜

"이번 달까지", "8월 31일까지"처럼 연도가 없는 표현은
영상 업로드 날짜를 기준으로 해석한다. 업로드 날짜를 알 수 없으면 연도가 없는 날짜는 비운다.
관찰 기록에 기간이 명확히 나오지 않으면 비운다.

## 요약

요약은 이 장소를 나중에 검색할 때 쓸 속성을 1~2문장으로 적는다.
좌석·소음·혼잡도·분위기·가격대·대표 메뉴나 볼거리처럼,
"조용한 곳", "혼자 가기 좋은 곳" 같은 조건으로 찾아낼 수 있는 내용을 쓴다.
위치(동네·건물·층·역)는 요약에 넣지 않는다 — 위치는 아래 위치 칸에 따로 적는다.

좋은 예: 통유리에 좌석 간격이 넓고 대화 소음이 적음
좋은 예: 책 읽는 손님 위주라 오래 머물기 좋고 노트북 사용 가능
나쁜 예: 분위기 좋은 감성 카페 (검색 조건이 될 수 없음)
나쁜 예: 꼭 가봐야 할 인생 맛집 (광고 문구)
나쁜 예: 성수역 근처 건물 1층 카페 (위치는 요약이 아니라 위치 칸에)

## 위치 (location_detail)

관찰 기록에 나온 건물명·층·가까운 역 출구를 적는다. 예: "OO빌딩 2층", "성수역 3번 출구 앞".
동네 이름만 있으면 지역(region)에 적고 이 칸은 비운다. 관찰 기록에 없으면 비운다.

## 신뢰도

추출한 장소 정보를 얼마나 믿을 수 있는지를 0과 1 사이로 매긴다.

- 0.9 이상  : 간판·자막·음성으로 장소명이 그대로 드러남
- 0.7 ~ 0.9 : 장소명은 나오지만 지점이나 지역이 불분명함
- 0.4 ~ 0.7 : 해시태그나 배경 일부로만 짐작됨
- 0.4 미만  : 장소를 특정할 수 없음

장소명을 비웠다면 신뢰도는 0.4를 넘지 않는다.
"""


# 관찰 기록은 사용자 메시지로 넣는다 — 화면 글자가 그대로 옮겨진 데이터라 지시와 섞지 않는다.
def build_extract_messages(observations: list[str], upload_date: date | None) -> list[BaseMessage]:
    uploaded = upload_date.isoformat() if upload_date else "알 수 없음"
    return [
        SystemMessage(content=EXTRACT_PROMPT),
        HumanMessage(content=f"업로드 날짜: {uploaded}\n\n관찰 기록:\n" + "\n".join(observations)),
    ]
